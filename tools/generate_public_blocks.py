def signatures() -> dict[str, list[tuple[str, str]]]:
    """Generate signatures from the canonical API schema."""
    result = {}
    for name in ("generic_blocks", "joint_blocks", "cartesian_blocks", "energy_tank"):
        source = (ROOT / f"src/nvidia/srl/controllers/tensor/{name}.hpp").read_text()
        for function, arguments in re.findall(r"Result (\w+)\((.*?)\);", source, re.S):
            result[function] = []
            for argument in arguments.split(","):
                kind, identifier = argument.strip().rsplit(None, 1)
                result[function].append((kind, identifier))
    return result


SIG = signatures()


def input_shape(block: Block, name: str) -> str:
    """Generate input shape from the canonical API schema."""
    if name == "dt":
        return "DT"
    if name in ("current_pose", "goal_pose", "cartesian_pose"):
        return "B,4,4"
    if name in ("power_signal", "additional_power"):
        return "B"
    if name in ("input_signal", "error", "command"):
        return "B,N"
    if name in ("joint_position_error", "joint_velocity_error", "joint_velocity"):
        return "B,J"
    if name == "joint_mass_matrix":
        return "B,J,J"
    if name == "stiffness_matrix" and block.name.startswith("Joint"):
        return "B,J,J"
    if name in ("stiffness_matrix", "cartesian_mass_matrix"):
        return "B,6,6"
    if name == "jacobian":
        return "B,6,J"
    return "B,6"


def outputs(block: Block) -> list[Array]:
    """Describe named result arrays."""
    result = []
    for kind, name in SIG[f"step_{block.backend}"]:
        if "MutableTensorView" not in kind:
            continue
        shape = (
            "B,N"
            if name in ("output_signal", "shaping_factor")
            else "B,J" if name == "joint_torque" else "B,6"
        )
        dtype = "float"
        if name in ("scale", "filtered_power", "command_is_valid"):
            shape = "B"
        if name == "command_is_valid":
            dtype = "bool"
        units = {
            "joint_torque": "Nm",
            "cartesian_wrench": "N_then_Nm",
            "cartesian_flow": "m/s_then_rad/s",
            "cartesian_acceleration": "m/s^2_then_rad/s^2",
            "scale": "unitless",
            "filtered_power": "W",
            "command_is_valid": "bool",
            "shaping_factor": "unitless",
        }.get(name, "caller_defined")
        result.append(Array(name, shape, dtype, units))
    return result


def inputs(block: Block) -> list[Array]:
    """Return read-only numeric operands."""
    return [
        Array(name, input_shape(block, name))
        for kind, name in SIG[f"step_{block.backend}"]
        if kind == "const TensorView&"
    ]


def shape_cpp(shape: str) -> str:
    """Generate shape cpp from the canonical API schema."""
    replacements = {"B": "c.batch_size", "N": "dimension", "J": "c.joint_dim"}
    return "{" + ", ".join(replacements.get(d, d) for d in shape.split(",") if d) + "}"


def dtype_cpp(dtype: str) -> str:
    """Generate dtype cpp from the canonical API schema."""
    return {"float": "c.dtype", "bool": "DType::kBool", "uint64": "DType::kUInt64"}[dtype]


def backend_name(block: Block, parameter: Array) -> str:
    """Generate backend name from the canonical API schema."""
    if parameter.shape == "MODE":
        return f'(config_.mode == ComponentMode::kDiagonal ? "{parameter.name}_diag" : "{parameter.name}_matrix")'
    return '"' + (parameter.backend or parameter.name) + '"'


