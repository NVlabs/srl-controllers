def setup(block: Block, parameter_object: str = "parameters_") -> str:
    """Generate setup from the canonical API schema."""
    text = "  const ControllerConfig c = block_config(config_);\n  const std::size_t dimension = block_dimension(config_);\n  (void)dimension;\n"
    text += f"  std::array<ParameterView, {len(block.parameters)}> parameter_entries{{}};\n  std::size_t parameter_count = 0;\n"
    for a in block.parameters:
        text += f"  append_parameter(&parameter_entries, &parameter_count, {backend_name(block, a)}, {parameter_object}.{a.name});\n"
    text += "  const auto parameters_view = parameter_set(parameter_entries, parameter_count);\n  (void)parameters_view;\n"
    for name, kind, fields in (
        ("state", "State", block.state),
        ("scratch", "Scratch", block.scratch),
    ):
        text += f"  std::array<{kind}EntryView, {len(fields)}> {name}_entries{{{{\n"
        text += ",\n".join(
            f'    {kind}EntryView{{"{a.backend or a.name}", storage_.{name}.{a.name}}}'
            for a in fields
        )
        text += f"\n  }}}};\n  {kind}View {name}{{{name}_entries.data(), {name}_entries.size()}};\n  (void){name};\n"
    text += "  (void)c;\n"
    text += "  detail::tensor::ScopedTensorExecutionContext scope(context);\n"
    return text


def backend_call(block: Block, operation: str) -> str:
    """Generate backend call from the canonical API schema."""
    name = f"{operation}_{block.backend}" + ("_parameters" if operation == "apply" else "")
    output_path = "storage_.output." if block.protected else "storage_."
    mapping = {
        "mode": "config_.mode",
        "parameters": "parameters_view",
        "num_envs": "c.batch_size",
        "joint_dim": "c.joint_dim",
        "signal_dim": "dimension",
        "parameter_status": output_path + "parameter_status",
        "status": output_path + "status",
        "state": "state",
        "scratch": "scratch",
        "reset_mask": "inputs.mask",
        "use_shaping_function": "config_.use_shaping_function",
    }
    if operation != "apply":
        mapping["parameter_status"] = "read_status(" + mapping["parameter_status"] + ")"
    mapping.update({a.name: "inputs." + a.name for a in inputs(block)})
    mapping.update(
        {
            a.name: "storage_.output.command" if block.protected else "storage_." + a.name
            for a in outputs(block)
        }
    )
    return "detail::tensor::" + name + "(" + ", ".join(mapping[arg] for _, arg in SIG[name]) + ")"


def implementation() -> str:
    """Generate implementation from the canonical API schema."""
    text = PREFIX
    for b in BLOCKS:
        text += f"\nResult {b.name}::requirements(const Config& config, Requirements* output) noexcept {{\n"
        text += '  if (!output) return invalid_argument("requirements output is null");\n  *output = Requirements{};\n  const ControllerConfig c = block_config(config);\n  const std::size_t dimension = block_dimension(config);\n  (void)dimension;\n'
        cartesian = b.config not in (
            "SignalBlockConfig",
            "JointBlockConfig",
        ) and not b.name.startswith("Joint")
        text += (
            "  Result result = "
            + (
                "validate_cartesian_config(c, "
                + str(bool(b.state and b.name != "VariableCartesianStiffness")).lower()
                + ")"
                if cartesian
                else "validate_config(c, " + str(b.name.startswith("Joint")).lower() + ")"
            )
            + ";\n  if (!result.ok()) return result;\n"
        )
        if b.config == "SignalBlockConfig":
            text += (
                '  if (dimension == 0) return invalid_argument("signal_dim must be positive");\n'
            )
        if b.name == "JointDampingDoubleDiagonalization":
            text += '  if (dimension > 32) return invalid_argument("double diagonalization requires joint_dim <= 32");\n'
        if b.name == "EnergyTank":
            text += '  if (dimension != 1) return invalid_argument("energy tank uses signal_dim == 1");\n'
        if b.config == "JointBlockConfig":
            text += '  if (config.mode != ComponentMode::kDiagonal && config.mode != ComponentMode::kDense) return invalid_argument("joint block mode must be diagonal or dense");\n'
        text += "  output->batch_size = c.batch_size;\n  output->joint_dim = c.joint_dim;\n"
        for group, fields in (("outputs", outputs(b)), ("state", b.state), ("scratch", b.scratch)):
            for i, a in enumerate(fields):
                name = (
                    ("output.command" if b.protected else a.name)
                    if group == "outputs"
                    else group + "." + a.name
                )
                text += (
                    f'  result = append_block_requirement(&output->{group}, &output->{ {"outputs": "output_count", "state": "state_count", "scratch": "scratch_count"}[group]}, "{name}", {dtype_cpp(a.dtype)}, c.device, {shape_cpp(a.shape)}, "{a.units}", '
                    + (
                        '"caller_defined"'
                        if b.config == "SignalBlockConfig"
                        else "cartesian_frame_name(c.cartesian_frame)"
                    )
                    + ");\n  if (!result.ok()) { *output = Requirements{}; return result; }\n"
                )
        for name in ("parameter_status", "status"):
            field = "output." + name if b.protected else name
            text += f'  result = append_block_requirement(&output->outputs, &output->output_count, "{field}", DType::kUInt64, c.device, {{c.batch_size}}, "status_flags", "none");\n  if (!result.ok()) {{ *output = Requirements{{}}; return result; }}\n'
        if b.protected:
            text += (
                "  result = append_safety_requirements(c, "
                + (
                    "dimension"
                    if b.config == "SignalBlockConfig"
                    else "c.joint_dim" if b.name.startswith("Joint") else "6"
                )
                + ', "caller_defined", "caller_defined", output);\n  if (!result.ok()) return result;\n'
            )
        if b.protected:
            text += '  output->state[output->state_count - 3].name = "output.safety.last_valid_output";\n  output->state[output->state_count - 2].name = "output.safety.valid_mask";\n  output->state[output->state_count - 1].name = "output.safety.hold_count";\n'
        text += "  return {};\n}\n"
        text += f"Result {b.name}::prepare(const Config& config, const Parameters& parameters, const Storage& storage, ExecutionContext context) noexcept {{\n  prepared_ = false;\n  Requirements description;\n  Result result = requirements(config, &description);\n  if (!result.ok()) return result;\n  const ControllerConfig c = block_config(config);\n  const std::size_t dimension = block_dimension(config);\n  (void)dimension;\n"
        if b.protected:
            dim = (
                "dimension"
                if b.config == "SignalBlockConfig"
                else "c.joint_dim" if b.name.startswith("Joint") else "6"
            )
            text += f"  result = validate_storage(c, storage.output, {dim});\n  if (!result.ok()) return result;\n"
        else:
            text += "  result = validate_block_status(c, storage.parameter_status, storage.status);\n  if (!result.ok()) return result;\n"
        own = []
        for group, fields in (
            ("outputs", outputs(b) if not b.protected else []),
            ("state", b.state),
            ("scratch", b.scratch),
        ):
            for a in fields:
                path = "storage." + (group + "." if group != "outputs" else "") + a.name
                own.append(path)
                text += f"  result = validate_block_array({path}, c, {dtype_cpp(a.dtype)}, {shape_cpp(a.shape)});\n  if (!result.ok()) return result;\n"
        if b.protected:
            own += [
                "storage.output.command",
                "storage.output.safety.last_valid_output",
                "storage.output.safety.valid_mask",
                "storage.output.safety.hold_count",
            ]
        prefix = "storage.output." if b.protected else "storage."
        own += [
            f"write_view({prefix}{name}.flags, c.device, c.batch_size)"
            for name in ("parameter_status", "status")
        ]
        text += (
            "  if (block_arrays_overlap({"
            + ", ".join(own)
            + '})) return invalid_view("mutable block storage must not overlap");\n'
        )
        text += "  config_ = config; parameters_ = parameters; storage_ = storage; prepared_ = true;\n  result = apply_parameters(parameters, context);\n  prepared_ = result.ok();\n  return result;\n}\n"
        text += f'Result {b.name}::apply_parameters(const Parameters& parameters, ExecutionContext context) noexcept {{\n  if (!prepared_) return invalid_argument("block is not prepared");\n'
        text += setup(b, "parameters")
        for a in b.parameters:
            shape = (
                shape_cpp(a.shape)
                if a.shape != "MODE"
                else "(config_.mode == ComponentMode::kDiagonal ? std::initializer_list<std::size_t>{c.joint_dim} : std::initializer_list<std::size_t>{c.joint_dim, c.joint_dim})"
            )
            text += f"  {{ const Result checked = validate_block_parameter(parameters.{a.name}, c, {shape});\n    if (!checked.ok()) {{ prepared_ = false; return checked; }} }}\n"
        mutable = ", ".join(path.replace("storage.", "storage_.") for path in own)
        for a in b.parameters:
            text += f'  if (block_input_overlaps(parameters.{a.name}.values, {{{mutable}}})) {{ prepared_ = false; return invalid_view("parameters must not overlap mutable storage"); }}\n'
        text += f"  const Result result = {backend_call(b, 'apply')};\n  prepared_ = result.ok();\n  if (prepared_) parameters_ = parameters;\n  return result;\n}}\n"
        for operation in ("reset", "step"):
            text += (
                f"Result {b.name}::{operation}(const {'ResetInputs' if operation == 'reset' else 'Inputs'}& inputs, ExecutionContext context) noexcept {{\n  if (!prepared_) return invalid_argument(\"block is not prepared\");\n"
                + setup(b)
            )
            if operation == "step":
                for a in inputs(b):
                    call = (
                        f"validate_block_dt(inputs.{a.name}, c)"
                        if a.shape == "DT"
                        else f"validate_block_array(inputs.{a.name}, c, c.dtype, {shape_cpp(a.shape)})"
                    )
                    text += f"  {{ const Result checked = {call}; if (!checked.ok()) return checked; }}\n"
                for a in inputs(b):
                    text += f'  if (block_input_overlaps(inputs.{a.name}, {{{mutable}}})) return invalid_view("inputs must not overlap mutable storage");\n'
            else:
                text += f'  if (inputs.mask.data && block_input_overlaps(inputs.mask, {{{mutable}}})) return invalid_view("reset mask must not overlap mutable storage");\n'
            text += f"  const Result result = {backend_call(b, operation)};\n"
            if b.protected:
                text += (
                    "  return "
                    + (
                        "result.ok() ? reset_safety(c, storage_.output, inputs) : result"
                        if operation == "reset"
                        else "finish_step(result, c, storage_.output)"
                    )
                    + ";\n}\n"
                )
            else:
                text += "  return result;\n}\n"
    return text


def write(path: Path, text: str, check: bool) -> None:
    """Format and write an adapter, or verify its freshness."""
    text = format_source(path, text)
    if check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f"Generated public API is stale: {path}")
    else:
        path.write_text(text)


